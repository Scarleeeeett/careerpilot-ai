import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { DatabaseSync } from "node:sqlite";
import { databaseRuntime, getMetricsSummary } from "../src/server/data/database.js";

const descriptions = {
  schema_migrations: "数据库迁移版本与执行时间",
  app_snapshots: "浏览器完整状态快照，用于首次迁移和恢复",
  resumes: "简历主记录，不含每次修改的正文",
  resume_versions: "简历正文、项目材料及内容哈希的历史版本",
  jobs: "公司、岗位、业务线、当前投递阶段等岗位主记录",
  jd_versions: "JD 原文和来源的不可覆盖历史版本",
  interview_sessions: "各岗位的面试轮次、原始笔记和关联准备运行",
  interview_questions: "真实问题、回答、思路、缺口和 AI 反馈",
  interview_reviews: "面试复盘的版本、准备快照、确定性指标和完整结构化结果",
  agent_runs: "每次 AI/规则任务的输入、输出、模型、耗时和 Token 汇总",
  agent_steps: "Agent Run 内逐 Skill 的执行顺序、摘要、耗时与错误",
  artifacts: "岗位分析、准备计划、求职信等可复用输出版本",
  metric_events: "迁移、同步和运行完成等可聚合事件",
  file_assets: "简历、JD 图片、音频等原文件的元数据和存储索引",
  application_stage_events: "岗位阶段从旧状态到新状态的变更历史",
  eval_runs: "一次评测的版本、通过数、总数与准确率",
  eval_case_results: "评测中每个样本的期望、实际结果和错误"
};

const db = new DatabaseSync(databaseRuntime.path, { readOnly: true });
const tables = db.prepare(`
  SELECT name, sql
  FROM sqlite_master
  WHERE type = 'table' AND name NOT LIKE 'sqlite_%' AND sql IS NOT NULL
  ORDER BY name
`).all();

const generatedAt = new Date().toISOString();
const tableCounts = Object.fromEntries(
  tables.map(({ name }) => [name, Number(db.prepare(`SELECT COUNT(*) AS count FROM "${name}"`).get().count)])
);
const schemaSql = [
  "-- Generated by npm run data:summary.",
  `-- Schema version: ${databaseRuntime.schemaVersion}; generated at ${generatedAt}.`,
  "-- Runtime source of truth: src/server/data/database.js",
  "",
  ...tables.flatMap(({ sql }) => [`${sql};`, ""])
].join("\n");

const metrics = getMetricsSummary();
const snapshot = {
  generatedAt,
  schemaVersion: databaseRuntime.schemaVersion,
  privacy: "Aggregates only. Resume, JD, interview text, model prompts and artifacts are excluded.",
  tableCounts,
  metrics
};

const catalogRows = tables.map(({ name }) => `| \`${name}\` | ${tableCounts[name]} | ${descriptions[name] || "运行数据表"} |`);
const catalog = [
  "# 数据目录",
  "",
  `生成时间：${generatedAt}  `,
  `Schema 版本：${databaseRuntime.schemaVersion}`,
  "",
  "本文件由 `npm run data:summary` 从本机 SQLite 生成。只展示表名、行数和用途，不包含简历、JD、面试记录、Prompt 或 AI 输出正文。",
  "",
  "| 数据表 | 当前行数 | 用途 |",
  "|---|---:|---|",
  ...catalogRows,
  "",
  "## 可量化成果",
  "",
  "- `agent_runs` / `agent_steps`：成功率、耗时、Token、失败步骤。",
  "- `eval_runs` / `eval_case_results`：按数据集版本追踪回归准确率和 badcase。",
  "- `interview_sessions` / `interview_questions` / `interview_reviews`：比较面试前准备与真实问题覆盖率，追踪回答和证据准备度。",
  "- `application_stage_events`：计算保存、投递、面试、Offer 等阶段转化。",
  "- `resume_versions` / `jd_versions` / `artifacts`：比较每次迭代前后的输入和输出。",
  "",
  "聚合结果见 [`metrics-snapshot.json`](./metrics-snapshot.json)，完整字段定义见 [`schema.sql`](./schema.sql)。"
].join("\n");

const dataDir = join(process.cwd(), "data");
writeFileSync(join(dataDir, "schema.sql"), schemaSql, "utf8");
writeFileSync(join(dataDir, "metrics-snapshot.json"), `${JSON.stringify(snapshot, null, 2)}\n`, "utf8");
writeFileSync(join(dataDir, "catalog.md"), `${catalog}\n`, "utf8");
db.close();

console.log(`Data summary generated: ${tables.length} tables, schema v${databaseRuntime.schemaVersion}.`);
